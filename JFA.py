import os

principal = float(input("Enter the Principal Amount: "))
rate = float(input("Enter the Rate of Interest: "))
time = float(input("Enter the Time Period in Years: "))
income = float(input("Enter Borrower's Monthly Income: "))
cibil = int(input("Enter Borrower's CIBIL Score (300 - 900): "))
os.system('clear')

print("Principal: ", principal)
print("Rate:", rate, "%")
print("Time:", time, "years")

#Upfront Proccessing fee (1% + 18% GST)

processing_fee = round(principal * 0.01, 2)
gst_on_fee = round(processing_fee * 0.18, 2)
total_upfront_fee = processing_fee + gst_on_fee
net_disbursed = principal - total_upfront_fee

print("---- LOAN DISBURSAL DETAILS ----")
print("Sanctioned Loan Amount: ₹", principal)
print("Processing Fee 1%: ₹", processing_fee)
print("GST on Fee 18%: ₹", gst_on_fee)
print("Net amount disbursed to borrower's Acount: ₹", net_disbursed)
print("------------------------------------")

#EMI calculation

def calculate_emi(P, R, T):
    r = R / (12 * 100)
    n = T * 12
    emi = P * r * (1+r)**n / ((1+r)**n -1)
    return round(emi, 2)

emi = calculate_emi(principal, rate, time)

#Bank credit Risk check

emi_ratio = round((emi / income) * 100, 2)
print("\n---- CREDIT RISK & APPROVAL STATUS ----")
print(f"Borrower's Monthly Income: ₹ {income:,.2f}")
print(f"CIBIL Score              : {cibil}")
print(f"EMI burden on Income      : {emi_ratio} %")

if cibil < 650:
        approval_status = "REJECTED (Credit Default Risk - CIBIL below 650)"
        print(f"STATUS: ❌ {approval_status}")
elif emi_ratio > 50:
        approval_status = "REJECTED (High Debt Burden - EMI exceeds 50% of income)"
        print(f"STATUS: ❌ {approval_status}")
elif cibil >= 750:
        approval_status = "APPROVED (Prime Borrower - Clean Track Record)"
        print(f"STATUS: ✅ {approval_status}")
else:
        approval_status = "CONDITIONAL APPROVAL (Moderate Risk - Requires Guarantor)"
        print(f"STATUS: ⚠️ {approval_status}")


total_paid = round(emi * time * 12, 2)
interest_paid = round(total_paid - principal, 2)

print("Monthly EMI: ", emi)
print("Total Paid over ", time, " years: ", total_paid)
print("Total Interest Paid: ", interest_paid)

tax_rate = 25
tax_amount = (interest_paid * tax_rate) / 100
bank_profit_after_tax = interest_paid - tax_amount

print("Bank Earnings before Tax: ", interest_paid)
print("Tax paid to Govt(25%): ", round(tax_amount, 2))
print("Bank Profit after Tax: ", round(bank_profit_after_tax, 2))

#EMI Month by Month chart

print("\n--- EMI Repayment Chart ---")
print(" Month |    EMI (₹) | Interest (₹) | Principal (₹) |   Balance (₹)")
print("-------+------------+--------------+---------------+--------------")

balance = principal
monthly_rate = rate / (12 * 100)
total_months = int(time * 12)

for month in range(1, total_months + 1):
    interest_this_month = round(balance * monthly_rate, 2)
    principal_this_month = round(emi - interest_this_month, 2)
    balance = round(balance - principal_this_month, 2)

    print(f"{month:>6} | {emi:>10.2f} | {interest_this_month:>12.2f} | {principal_this_month:>13.2f} | {max(balance, 0):>12.2f}")

save_choice = input("\nDo you want to download this statement? (y/n): ")

if save_choice.lower() == 'y':
    filename = "Jadhav_Loan_Statement.txt"
    with open(filename, "w") as f:
        f.write("=================================================================\n")
        f.write("             JADHAV FINANCIAL GROUP - LOAN SANCTION STATEMENT    \n")
        f.write("=================================================================\n\n")
        f.write(f"Sanctioned Loan Amount : ₹ {principal:,.2f}\n")
        f.write(f"Annual Interest Rate   : {rate} %\n")
        f.write(f"Tenure                 : {time} Years ({total_months} Months)\n")
        f.write(f"Monthly EMI            : ₹ {emi:,.2f}\n")
        f.write(f"Net Disbursed Amount   : ₹ {net_disbursed:,.2f}\n")
        f.write(f"Borrower CIBIL Score   : {cibil}\n")
        f.write(f"Credit Approval Status : {approval_status}\n\n")
        f.write("-----------------------------------------------------------------\n")
        f.write(" Month |    EMI (₹) | Interest (₹) | Principal (₹) |   Balance (₹)\n")
        f.write("-------+------------+--------------+---------------+--------------\n")
        
        # Write ALL months into the file too!
        temp_balance = principal
        for m in range(1, total_months + 1):
            m_interest = round(temp_balance * monthly_rate, 2)
            m_principal = round(emi - m_interest, 2)
            temp_balance = round(temp_balance - m_principal, 2)
            f.write(f"{m:>6} | {emi:>10.2f} | {m_interest:>12.2f} | {m_principal:>13.2f} | {max(temp_balance, 0):>12.2f}\n")
            
        f.write("=================================================================\n")
        f.write("Generated by Jadhav Financial Lab Engine | Author: Raj Jadhav\n")

    print(f"\n✅ Statement successfully downloaded to: {filename}")
